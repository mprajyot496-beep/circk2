def num_hi(n):
    """Integer as Hindi words. 237 -> 'दो सौ सैंतीस'."""
    try:
        n = int(n)
    except (TypeError, ValueError):
        return ""
    if n < 0:
        return ""
    if n < 100:
        return NUM_HI.get(n, str(n))
    for base, word in _SCALE:
        if n >= base:
            head, rest = divmod(n, base)
            out = "%s %s" % (num_hi(head), word)
            return "%s %s" % (out, num_hi(rest)) if rest else out
    return str(n)


# Hindi ordinals are irregular below 11 - "तीनवां" is wrong, it is "तीसरा".
_ORD_M = {
    1: "पहला", 2: "दूसरा", 3: "तीसरा", 4: "चौथा", 5: "पांचवां",
    6: "छठा", 7: "सातवां", 8: "आठवां", 9: "नौवां", 10: "दसवां",
}


def ordinal_hi(n):
    """Masculine ordinal: 3 -> 'तीसरा', 14 -> 'चौदहवां'."""
    try:
        n = int(n)
    except (TypeError, ValueError):
        return ""
    if n in _ORD_M:
        return _ORD_M[n]
    return "%sवां" % num_hi(n)


def ordinal_over(n):
    """14 -> 'चौदहवें ओवर'. Small numbers get their irregular Hindi form."""
    try:
        n = int(n)
    except (TypeError, ValueError):
        return ""
    if n in _ORDINAL:
        return "%s ओवर" % _ORDINAL[n]
    return "%sवें ओवर" % num_hi(n)


def rate_hi(v):
    """Run rate as speakable Hindi: 8.25 -> 'आठ दशमलव दो पांच'."""
    try:
        v = float(v)
    except (TypeError, ValueError):
        return ""
    whole = int(v)
    dec = int(round((v - whole) * 100))
    if dec % 10 == 0:
        dec //= 10
        digits = [dec] if dec else []
    else:
        digits = [dec // 10, dec % 10]
    if not digits:
        return num_hi(whole)
    return "%s दशमलव %s" % (num_hi(whole), " ".join(num_hi(d) for d in digits))


# Feminine ordinals, for balls: "ओवर की तीसरी गेंद".
_ORD_F = {1: "पहली", 2: "दूसरी", 3: "तीसरी", 4: "चौथी", 5: "पांचवीं",
          6: "छठी", 7: "सातवीं", 8: "आठवीं"}


def ordinal_f(n):
    """Feminine ordinal: 3 -> 'तीसरी'. Empty outside 1-8."""
    try:
        return _ORD_F.get(int(n), "")
    except (TypeError, ValueError):
        return ""


def ball_of_over(metric):
    """Cricbuzz ballMetric 13.3 -> (14, 3): the 14th over, its 3rd ball."""
    try:
        v = float(metric)
    except (TypeError, ValueError):
        return None
    over = int(v)
    ball = int(round((v - over) * 10))
    if not 1 <= ball <= 6:
        return None
    return over + 1, ball


def wickets_hi(w):
    """'एक विकेट' / 'तीन विकेट्स' - the reference stream says विकेट्स."""
    w = int(w or 0)
    return "%s %s" % (num_hi(w), "विकेट" if w == 1 else "विकेट्स")


